-- Raw schema: demo proxy views, consumer staging tables for all data sources
-- Co-authored with CoCo

CREATE SCHEMA IF NOT EXISTS raw;
GRANT USAGE ON SCHEMA raw TO APPLICATION ROLE app_user;
GRANT USAGE ON SCHEMA raw TO APPLICATION ROLE app_admin;

-- ── Demo views (populated from SHARED_DATA when available) ──
CREATE OR REPLACE VIEW raw.demo_contracts AS
    SELECT CONTRACT_ID, CUSTOMER_ID, ANNUAL_VALUE_USD, PENALTY_PCT,
           SLA_HOURS, UNIT_RATE_USD, CONTRACTED_UNITS, OVERAGE_RATE_USD,
           BONUS_PCT, BONUS_THRESHOLD_HRS, DELIVERY_SLA_PCT, DEFECT_SLA_PCT,
           CONTRACT_TYPE, CONTRACT_START_DATE, CONTRACT_END_DATE
    FROM SHARED_DATA.DEMO_CONTRACTS;

CREATE OR REPLACE VIEW raw.demo_customers AS
    SELECT CUSTOMER_ID, CUSTOMER_NAME, INDUSTRY, SEGMENT, REGION, COUNTRY
    FROM SHARED_DATA.DEMO_CUSTOMERS;

CREATE OR REPLACE VIEW raw.demo_billing_transactions AS
    SELECT TRANSACTION_ID, CONTRACT_ID, CUSTOMER_ID, TRANSACTION_DATE,
           BILLED_AMOUNT, UNIT_PRICE, QUANTITY, PAYMENT_STATUS, INVOICE_NUMBER
    FROM SHARED_DATA.DEMO_BILLING_TRANSACTIONS;

CREATE OR REPLACE VIEW raw.demo_operational_events AS
    SELECT EVENT_ID, CONTRACT_ID, CUSTOMER_ID, EVENT_TYPE, EVENT_DATE,
           TURNAROUND_HOURS, UPTIME_PCT, OVERAGE_UNITS, STATUS,
           REPORTED_VALUE, DELIVERY_PCT, DEFECT_PCT
    FROM SHARED_DATA.DEMO_OPERATIONAL_EVENTS;

GRANT SELECT ON ALL VIEWS IN SCHEMA raw TO APPLICATION ROLE app_user;

