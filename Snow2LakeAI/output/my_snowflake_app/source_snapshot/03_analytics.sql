-- Analytics schema: leakage events, alerts, credit notes
-- Co-authored with CoCo

CREATE SCHEMA IF NOT EXISTS analytics;
GRANT USAGE ON SCHEMA analytics TO APPLICATION ROLE app_user;
GRANT USAGE ON SCHEMA analytics TO APPLICATION ROLE app_admin;

CREATE OR REPLACE TABLE analytics.leakage_events (
    LEAKAGE_ID            STRING DEFAULT UUID_STRING() NOT NULL,
    RULE_ID               STRING NOT NULL,
    RULE_NAME             STRING NOT NULL,
    EVENT_REF             STRING NOT NULL,
    CONTRACT_ID           STRING NOT NULL,
    CUSTOMER_ID           STRING,
    CUSTOMER_NAME         STRING,
    INDUSTRY              STRING,
    LEAKAGE_TYPE          STRING NOT NULL,
    LEAKAGE_AMOUNT_USD    NUMBER(18,2) NOT NULL,
    SEVERITY              STRING NOT NULL,
    EVENT_DATE            DATE,
    CALCULATION_DETAIL    STRING,
    DATA_MODE             STRING,
    DETECTED_AT           TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_LEAKAGE PRIMARY KEY (LEAKAGE_ID)
);

CREATE OR REPLACE TABLE analytics.alert_log (
    ALERT_ID              STRING DEFAULT UUID_STRING() NOT NULL,
    LEAKAGE_ID            STRING NOT NULL,
    CONTRACT_ID           STRING,
    CUSTOMER_NAME         STRING,
    ALERT_TYPE            STRING,
    SEVERITY              STRING,
    LEAKAGE_AMOUNT_USD    NUMBER(18,2),
    ALERT_MESSAGE         STRING,
    SENT_TO               STRING,
    ALERT_CHANNEL         STRING DEFAULT 'EMAIL',
    STATUS                STRING DEFAULT 'PENDING',
    CREATED_AT            TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    RESOLVED_AT           TIMESTAMP_TZ,
    CONSTRAINT PK_ALERTS PRIMARY KEY (ALERT_ID)
);

CREATE OR REPLACE TABLE analytics.credit_notes (
    CREDIT_NOTE_ID        STRING DEFAULT UUID_STRING() NOT NULL,
    LEAKAGE_ID            STRING NOT NULL,
    CONTRACT_ID           STRING,
    CUSTOMER_NAME         STRING,
    CREDIT_TYPE           STRING,
    CREDIT_AMOUNT_USD     NUMBER(18,2),
    JUSTIFICATION         STRING,
    STATUS                STRING DEFAULT 'DRAFT',
    GENERATED_BY          STRING DEFAULT 'RULE_ENGINE',
    CREATED_AT            TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    APPROVED_AT           TIMESTAMP_TZ,
    APPROVED_BY           STRING,
    ERP_SYNC_STATUS       STRING DEFAULT 'PENDING',
    CONSTRAINT PK_CREDITS PRIMARY KEY (CREDIT_NOTE_ID)
);

GRANT SELECT ON ALL TABLES IN SCHEMA analytics TO APPLICATION ROLE app_user;
GRANT ALL ON ALL TABLES IN SCHEMA analytics TO APPLICATION ROLE app_admin;
